import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Optional

from ..config import settings
from .resilience import call_with_resilience, CircuitOpenError


def _send_via_smtp(to_email: str, msg: MIMEMultipart) -> None:
    with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT, timeout=15) as server:
        server.starttls()
        server.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
        server.sendmail(settings.SMTP_USER, [to_email], msg.as_string())


def _send_email(to_email: str, subject: str, body: str) -> tuple[bool, Optional[str]]:
    """Shared real-SMTP send with retry+backoff (services/resilience.py).
    Returns (ok, error_message) — error_message is None on success, and is
    specific enough (not configured vs. circuit open vs. send failure) for a
    caller to persist an honest, actionable status rather than a bare bool."""
    if not (settings.SMTP_HOST and settings.SMTP_USER and settings.SMTP_PASSWORD):
        msg = "SMTP is not configured on the server (SMTP_HOST/SMTP_USER/SMTP_PASSWORD unset)."
        print(f"[Email Service] {msg} — skipping send.")
        return False, msg

    email = MIMEMultipart()
    email["From"] = settings.SMTP_USER
    email["To"] = to_email
    email["Subject"] = subject
    email.attach(MIMEText(body, "plain"))

    try:
        call_with_resilience(
            "smtp", _send_via_smtp, to_email, email,
            max_attempts=3, base_delay=0.5, max_delay=4.0,
        )
        return True, None
    except CircuitOpenError as e:
        error = f"Email delivery temporarily unavailable (too many recent SMTP failures): {e}"
        print(f"[Email Service Error] {error}")
        return False, error
    except Exception as e:
        error = f"SMTP send failed after retries: {e}"
        print(f"[Email Service Error] {error}")
        return False, error


def send_invite_email(to_email: str, role_title: str, interview_link: str, when: Optional[str] = None) -> bool:
    subject = f"Your AI Screening Interview — {role_title}"
    timing = f" It's scheduled for {when}." if when else ""
    body = (
        f"Hi,\n\nYou've been invited to a first-round AI screening interview for the "
        f"{role_title} role.{timing}\n\nWhen you're ready, click the link below to begin:\n"
        f"{interview_link}\n\nA few tips before you start:\n"
        "- Use a quiet room with a working camera and microphone.\n"
        "- Have your resume ready (PDF only).\n"
        "- The interviewer asks about six questions; it usually takes 10-15 minutes.\n\n"
        "Good luck!\nAgenticFlow"
    )
    ok, _ = _send_email(to_email, subject, body)
    return ok


def send_assignment_email(
    to_email: str, candidate_name: str, role_title: str, assignment: dict
) -> tuple[bool, Optional[str]]:
    """Sends the real take-home assignment brief generated by
    services/hiring_service.py::generate_assignment to a shortlisted
    candidate. Used by the hiring-automation 'Bulk Send Assignment' flow —
    replaces what used to be a client-side animation with zero email sent."""
    title = assignment.get("title", "Take-Home Assignment")
    duration = assignment.get("duration", "")
    requirements = assignment.get("requirements") or []
    submission = assignment.get("submission", "")

    subject = f"Your Take-Home Assignment — {role_title}"
    req_lines = "\n".join(f"- {r}" for r in requirements) if requirements else "(see attached brief)"
    body = (
        f"Hi {candidate_name},\n\n"
        f"Thanks for your interest in the {role_title} role. As the next step, please complete "
        f"the take-home assignment below.\n\n"
        f"Assignment: {title}\n"
        f"Time allowed: {duration}\n\n"
        f"Requirements:\n{req_lines}\n\n"
        f"Submission: {submission}\n\n"
        "Please reply to this email once you've submitted, or if you have any questions.\n\n"
        "Best,\nAgenticFlow Hiring Team"
    )
    return _send_email(to_email, subject, body)
